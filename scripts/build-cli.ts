/**
 * Build the self-contained skill bundle committed at skills/agent-recall-axi/scripts/agent-recall-axi.mjs
 * (specs/architecture.md#the-skill-bundle). Every dependency is inlined so the bundle runs under
 * plain `node` >= 22 from a skill install: no npm install, no node_modules, no registry.
 *
 *   bun scripts/build-cli.ts            # write the bundle (bun run build:bundle)
 *   bun scripts/build-cli.ts --check    # fail if the committed bundle is stale (bun run check:bundle)
 *   bun scripts/build-cli.ts --stamp 0.1.0   # a release build: stamp exactly this version (RELEASING.md)
 *
 * The version is stamped from `git describe`, or from `--stamp` for the release commit: the
 * release tag lands on main's merge commit, which develop never reaches, so `git describe` on
 * develop cannot name the release. Committing the bundle moves the sha (and a CI
 * checkout may lack tags), so --check replaces the one stamped literal on both sides before
 * comparing: a commit that only moves the sha passes, any other byte change fails.
 */
import { execFileSync } from "node:child_process";
import { chmodSync, readFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import * as esbuild from "esbuild";

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
export const OUTFILE = join(ROOT, "skills", "agent-recall-axi", "scripts", "agent-recall-axi.mjs");
const ENTRY = join(ROOT, "bin", "agent-recall-axi.ts");

function git(args: string[]): string | undefined {
  try {
    return execFileSync("git", args, { cwd: ROOT, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim() || undefined;
  } catch {
    return undefined;
  }
}

/** `git describe` of the newest `v*` tag without its `v`, else `<package.json version>-g<sha>`. */
export function stampVersion(): string {
  const described = git(["describe", "--tags", "--match", "v[0-9]*"]);
  if (described) return described.replace(/^v/, "");
  const pkg = JSON.parse(readFileSync(join(ROOT, "package.json"), "utf8")) as { version: string };
  const sha = git(["rev-parse", "--short", "HEAD"]);
  return sha ? `${pkg.version}-g${sha}` : pkg.version;
}

const RELEASE_VERSION = /^\d+\.\d+\.\d+(?:-rc\.\d+)?$/;

/** The `--stamp <version>` (or `--stamp=<version>`) argument, validated; undefined when absent. */
export function stampArg(argv: string[]): string | undefined {
  const i = argv.findIndex((a) => a === "--stamp" || a.startsWith("--stamp="));
  if (i < 0) return undefined;
  const value = argv[i]!.includes("=") ? argv[i]!.slice("--stamp=".length) : argv[i + 1];
  if (!value || !RELEASE_VERSION.test(value)) {
    throw new Error(`--stamp takes a release version like 0.1.0 or 0.2.0-rc.1 (no leading v), got ${JSON.stringify(value ?? "")}`);
  }
  return value;
}

/** The stamped literal as esbuild compiles src/version.ts (`VERSION = true ? "<v>" : readVersion()`). */
const STAMP = /(\bVERSION = true \? )"[^"\\\n]*"( : readVersion\(\))/g;

/** The bundle with its one version literal replaced; throws unless exactly one is found. */
export function normalizeVersion(source: string): string {
  const matches = source.match(STAMP) ?? [];
  if (matches.length !== 1) throw new Error(`expected one stamped version literal in the bundle, found ${matches.length}`);
  return source.replace(STAMP, '$1"__VERSION__"$2');
}

export async function buildBundle(version: string, write: boolean): Promise<string> {
  const result = await esbuild.build({
    entryPoints: [ENTRY],
    outfile: OUTFILE,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    legalComments: "none",
    // Paths in the output stay relative to the repo, so no machine's layout is baked in.
    absWorkingDir: ROOT,
    define: { __AGENT_RECALL_AXI_VERSION__: JSON.stringify(version) },
    // The entry's own shebang stays first; esbuild puts the banner after it.
    banner: {
      js: "// GENERATED by scripts/build-cli.ts from bin/ and src/; do not edit. Run `bun run build:bundle`.",
    },
    write: false,
    logLevel: "warning",
  });
  const text = stripModuleComments(result.outputFiles[0]!.text);
  if (write) {
    const { writeFileSync } = await import("node:fs");
    writeFileSync(OUTFILE, text);
    chmodSync(OUTFILE, 0o755);
  }
  return text;
}

/**
 * esbuild marks each module with a `// <path>` comment line (`// node_modules/…/index.js`,
 * `// src/lib/ids.ts`); those depend on the dependency layout, not on the code, so they go.
 */
export function stripModuleComments(text: string): string {
  return text.replace(/^[ \t]*\/\/ (?:node_modules|src|bin)\/[^\n]*\.(?:[cm]?js|ts)\n/gm, "");
}

/** Fresh build vs the committed bundle, version normalized out of both. */
export function bundleMatches(generated: string, committed: string): boolean {
  return normalizeVersion(generated) === normalizeVersion(committed);
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  const rel = relative(process.cwd(), OUTFILE);
  let stamp: string | undefined;
  try {
    stamp = stampArg(process.argv.slice(2));
  } catch (error) {
    console.error((error as Error).message);
    process.exit(2);
  }
  const version = stamp ?? stampVersion();
  const generated = await buildBundle(version, !check);
  if (check) {
    let committed: string;
    try {
      committed = readFileSync(OUTFILE, "utf8");
    } catch {
      console.error(`${rel} is missing; run \`bun run build:bundle\` and commit the result`);
      process.exit(1);
    }
    if (!bundleMatches(generated, committed)) {
      console.error(`${rel} is out of date; run \`bun run build:bundle\` and commit the result`);
      process.exit(1);
    }
    console.log(`${rel} is up to date`);
  } else {
    console.log(`Wrote ${rel} (${generated.length} bytes, version ${version})`);
  }
}
